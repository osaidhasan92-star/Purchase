const assert = require('node:assert/strict');
const path = require('node:path');
module.exports = async (page, base) => {
 const request = page.context().request;
 const me = await (await request.get(base+'/api/auth/me')).json();
 let n=0;
 const get = async p => {const r=await request.get(base+'/api'+p);assert.equal(r.status(),200,await r.text());return r.json()};
 const post = async (p,data) => {const r=await request.post(base+'/api'+p,{headers:{'X-CSRF-Token':me.csrfToken},data:{...data,requestKey:'production-actual-browser-'+Date.now()+'-'+(++n)}});assert.equal(r.status(),200,await r.text());return (await r.json()).record};
 const raw=await post('/products',{name:'Actual production raw',sku:'ACTUAL-RAW',rate:10});
 const output=await post('/products',{name:'Actual production finished',sku:'ACTUAL-FIN',rate:50});
 let state=(await get('/inventory/products/'+raw.id)).record;
 await post('/inventory/commands/adjust',{productId:raw.id,version:state.version,quantity:12,unitCost:10,reason:'Actual production setup'});
 const bom=await post('/production/commands/bom',{name:'Actual production BoM',productId:output.id,quantity:1,conversionCost:5,components:[{productId:raw.id,quantity:2}]});
 let order=await post('/production/commands/order',{bomId:bom.id,bomVersion:bom.version,quantity:4});
 const goto=async id => {await page.goto(base+'/erp.html?view=production-orders&orderId='+id);await page.getByRole('dialog').getByRole('heading',{name:/Manufacturing Order/}).waitFor()};
 await goto(order.id);
 await page.getByRole('button',{name:'Confirm Order',exact:true}).click();
 await page.getByRole('button',{name:'Stage Materials',exact:true}).waitFor();
 const staging = page.waitForResponse(response => response.url().endsWith('/production/commands/stage') && response.request().method() === 'POST');
 await page.getByRole('button',{name:'Stage Materials',exact:true}).click();
 assert.equal((await staging).status(),200);
 await page.getByRole('dialog').getByRole('cell',{name:'8.0000',exact:true}).first().waitFor();
 state=(await get('/inventory/products/'+raw.id)).record;
 assert.equal(Number(state.locations.Production),8);assert.equal(Number(state.quantity),12);assert.equal(Number(state.value),120);
 for(const width of [1366,390]) {
   await page.setViewportSize({width,height:900});
   await page.getByRole('button',{name:'Complete Production',exact:true}).click();
   const dialog=page.getByRole('dialog',{name:/Record Production/});await dialog.waitFor();
   assert.ok((await dialog.boundingBox()).width<=width);
   await dialog.getByRole('button',{name:'Cancel',exact:true}).scrollIntoViewIfNeeded();
   await page.screenshot({path:path.join(__dirname,'../test-results/production-actual-'+width+'.png')});
   await dialog.getByRole('button',{name:'Cancel',exact:true}).click();
 }
 await page.setViewportSize({width:1366,height:900});
 await page.getByRole('button',{name:'Complete Production',exact:true}).click();
 await page.getByLabel('Finished quantity',{exact:true}).fill('2');
 assert.equal(await page.getByLabel('Consumed quantity',{exact:true}).inputValue(),'4.0000');
 await page.getByLabel('Consumed quantity',{exact:true}).fill('4.2');
 await page.getByLabel('Scrap quantity',{exact:true}).fill('.3');
 await page.getByLabel('Actual conversion cost (PKR)',{exact:true}).fill('8');
 await page.getByRole('button',{name:'Post Production',exact:true}).click();
 await page.getByRole('dialog').getByText('Posted actual cost: PKR 50.00',{exact:true}).waitFor();
 const parent=(await get('/production/orders/'+order.id)).record;
 assert.equal(Number(parent.productionResult.scrapCost),3);
 const link=page.getByRole('dialog').getByRole('link',{name:parent.productionResult.backorderNumber,exact:true});
 await link.click();await page.getByRole('dialog').getByRole('heading',{name:'Manufacturing Order '+parent.productionResult.backorderNumber,exact:true}).waitFor();
 await page.getByRole('button',{name:'Complete Production',exact:true}).click();
 assert.equal(await page.getByLabel('Finished quantity',{exact:true}).inputValue(),'2.0000');
 await page.getByRole('button',{name:'Post Production',exact:true}).click();
 await page.getByRole('dialog').getByText('Posted actual cost: PKR 50.00',{exact:true}).waitFor();
 state=(await get('/inventory/products/'+output.id)).record;
 assert.equal(Number(state.quantity),4);assert.equal(Number(state.value),100);
 assert.equal(Number((await get('/finance/summary')).balanceCheck),0);
 console.log('Actual manufacturing: reservations, staging, partial production, scrap, linked remainder, costs and desktop/mobile Cancel passed');
};
